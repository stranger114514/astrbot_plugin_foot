def _default_gallery() -> dict:
    """返回默认图库配置结构。"""
    return {"overrides": {}, "added": [], "removed": []}


def load_gallery() -> dict:
    """读取面板编辑的图库配置；文件不存在或损坏时返回默认结构。"""
    if GALLERY_PATH.exists():
        try:
            data = json.loads(GALLERY_PATH.read_text(encoding="utf-8"))
            if isinstance(data, dict):
                merged = _default_gallery()
                merged.update(data)
                merged["overrides"] = merged.get("overrides") or {}
                merged["added"] = merged.get("added") or []
                merged["removed"] = merged.get("removed") or []
                return merged
        except Exception:
            pass
    return _default_gallery()


def save_gallery(gallery: dict) -> None:
    """把面板编辑的图库配置写回 data/gallery.json。"""
    GALLERY_DIR.mkdir(parents=True, exist_ok=True)
    data = _default_gallery()
    data.update(gallery or {})
    GALLERY_PATH.write_text(
        json.dumps(data, ensure_ascii=False, indent=2), encoding="utf-8"
    )


def build_characters(gallery: dict | None = None):
    """返回角色列表，每项为 dict：name/file/cls/story/taste。

    gallery 结构：
        overrides: {角色名: {story, taste}}  覆盖内置/自定义文案
        added:     [{name, file, cls, story, taste}]  面板新增角色
        removed:   [角色名]  屏蔽的内置角色
    """
    gallery = gallery or load_gallery()
    overrides = gallery.get("overrides") or {}
    added = gallery.get("added") or []
    removed = set(gallery.get("removed") or [])

    result = []
    for name, file, cls in CHAR_ROWS:
        if name in removed:
            continue
        custom = CUSTOM.get(name) or {}
        ov = overrides.get(name) or {}
        result.append({
            "name": name,
            "file": file,
            "cls": cls,
            "story": ov.get("story") if ov.get("story") is not None else custom.get("story"),
            "taste": ov.get("taste") if ov.get("taste") is not None else custom.get("taste"),
        })

    for item in added:
        if not isinstance(item, dict) or not item.get("name"):
            continue
        result.append({
            "name": item.get("name"),
            "file": item.get("file") or "",
            "cls": item.get("cls") or "",
            "story": item.get("story") or None,
            "taste": item.get("taste") or None,
        })

    return result
