def build_characters():
    """返回角色列表，每项为 dict：name/file/cls/story/taste。"""
    result = []
    for name, file, cls in CHAR_ROWS:
        custom = CUSTOM.get(name)
        if custom:
            result.append({
                "name": name, "file": file, "cls": cls,
                "story": custom["story"], "taste": custom["taste"],
            })
        else:
            result.append({
                "name": name, "file": file, "cls": cls,
                "story": None, "taste": None,
            })
    return result
